import path from 'node:path';
import { readJson, SerialQueue, writeFileAtomic } from './json-file.js';

interface MonthlyUsage {
  /** calendar month, YYYY-MM (UTC) */
  month: string;
  images: number;
}

interface UsageFile {
  version: 1;
  users: Record<string, MonthlyUsage>;
}

export class QuotaExceededError extends Error {
  constructor(readonly remaining: number) {
    super(remaining > 0
      ? `only ${remaining} image(s) left this month`
      : 'the monthly image quota is used up');
  }
}

/** Current month in UTC, e.g. 2026-10 */
export function currentMonth(now = new Date()): string {
  return now.toISOString().slice(0, 7);
}

/**
 * Images generated by each user this month (ai-usage.json). Images are reserved
 * before calling the provider, so simultaneous requests cannot exceed the quota,
 * and released if the generation fails.
 */
export class AiUsageStore {
  private usage: Record<string, MonthlyUsage> = {};
  private readonly file: string;
  private readonly queue = new SerialQueue();

  constructor(dataDir: string, private readonly clock: () => Date = () => new Date()) {
    this.file = path.join(dataDir, 'ai-usage.json');
  }

  async load(): Promise<void> {
    this.usage = (await readJson<UsageFile>(this.file, { version: 1, users: {} })).users ?? {};
  }

  private save(): Promise<void> {
    const content: UsageFile = { version: 1, users: this.usage };
    return writeFileAtomic(this.file, JSON.stringify(content, null, 2));
  }

  /** Images used this month by a user */
  used(userId: string): number {
    const entry = this.usage[userId];
    return entry && entry.month === currentMonth(this.clock()) ? entry.images : 0;
  }

  /** Reserves images for a generation; throws QuotaExceededError if the quota does not allow it */
  reserve(userId: string, count: number, quota: number): Promise<void> {
    return this.queue.run(async () => {
      const used = this.used(userId);
      if (used + count > quota) {
        throw new QuotaExceededError(Math.max(0, quota - used));
      }
      this.usage[userId] = { month: currentMonth(this.clock()), images: used + count };
      await this.save();
    });
  }

  /** Gives back images that were reserved but not produced (failed generation) */
  release(userId: string, count: number): Promise<void> {
    return this.queue.run(async () => {
      const entry = this.usage[userId];
      if (entry && entry.month === currentMonth(this.clock())) {
        entry.images = Math.max(0, entry.images - count);
        await this.save();
      }
    });
  }

  forget(userId: string): Promise<void> {
    return this.queue.run(async () => {
      delete this.usage[userId];
      await this.save();
    });
  }
}
